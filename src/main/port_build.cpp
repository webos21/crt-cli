fs::path port_ranlib_for(const fs::path& archiver) { return ranlib_beside(archiver); }

fs::path port_os_sdk(const Toolchain& toolchain) {
    if (!toolchain.os_sdk.empty()) return toolchain.os_sdk;
    if (toolchain.contract.contains("external_os_sdk")) return toolchain.contract.at("external_os_sdk").get<std::string>();
    return {};
}

Json port_declared_environment(const PortRecipe& recipe) {
    Json ops = Json::array();
    for (const auto& op : recipe.env) ops.push_back({{"name", op.name}, {"value", op.value}, {"append_flags", op.append_flags}});
    Json declared{{"defaults", flag_defaults()}, {"recipe", ops}};
    // Executor policy beyond the recipe (macOS) is part of what the build depends on; Linux has none, so its keys are unchanged.
    const auto& adapter = port_adapter_for(recipe.recipe_sha256);
    const auto& extra = port_executor_env(adapter, recipe.target_os);
    const auto& make_args = port_executor_make_args(adapter, recipe.target_os);
    if (!extra.empty() || !make_args.empty()) {
        Json executor = Json::array();
        for (const auto& op : extra) executor.push_back({{"name", op.name}, {"value", op.value}, {"append_flags", op.append_flags}});
        declared["executor"] = {{"env", executor}, {"make_args", make_args}};
    }
    return declared;
}

std::map<std::string, std::string> port_build_environment(const PortBuildRequest& request, const fs::path& prefix) {
    const auto& toolchain = *request.toolchain;
    const auto& recipe = request.recipe;
    auto base = request.tools->environment(request.job, toolchain.sdk);
    std::map<std::string, std::string> env;
    for (const auto& item : base.values) { auto eq = item.find('='); env[item.substr(0, eq)] = item.substr(eq + 1); }

    require(!toolchain.sdk.empty() && fs::is_directory(toolchain.sdk), "the port build needs an installed SDK");
    // POSIX hosts keep the single-word rule for every declared tool; on Windows the compiler and linker reach the build through
    // quoted wrapper scripts and the archiver and ranlib through their own (tool_word).
    if (!on_windows())
        for (const auto& tool : {toolchain.cc, toolchain.cxx, toolchain.linker})
            require_plain_word(tool.string(), "toolchain path");
    auto ranlib = ranlib_beside(toolchain.archiver);
    auto target = native_target();
    // The SDK's compiler wrappers are POSIX sh scripts; a script started through its #!/bin/sh line would run under the
    // host's sh, so they are always started as `<bundle sh> <script>` (the oracle does the same on Windows). The job's own
    // wrappers live at /crt-bin in the job rootfs, the SDK at /crt-sdk: one shell word whatever the real paths contain.
    env["CC"] = shell_path(*request.tools) + " /crt-bin/crt-cc";
    env["CXX"] = shell_path(*request.tools) + " /crt-bin/crt-c++";
    env["AR"] = tool_word(shell_path(*request.tools), "crt-ar", toolchain.archiver);
    env["RANLIB"] = tool_word(shell_path(*request.tools), "crt-ranlib", ranlib);
    env["CRT_HOST_CC"] = word(toolchain.cc);
    env["CRT_HOST_CXX"] = word(toolchain.cxx);
    env["CRT_TARGET_OS"] = target.at("os").get<std::string>();
    env["CRT_TARGET_ARCH"] = target.at("arch").get<std::string>();
    // Project-owned search paths travel in dedicated variables, never inside CPPFLAGS/LDFLAGS (a space-containing
    // prefix would lose its word boundary), exactly as the oracle does.
    env["CRT_PORT_INCLUDE_DIR"] = word(prefix / "include");
    env["CRT_PORT_LIBRARY_DIR"] = word(prefix / "lib");
    // crt-cc adds `-Wl,-rpath,$CRT_PORT_RPATH_DIR` to every link. During the build that would stamp the job's prefix into
    // each installed library (a path that stops existing the moment the item is published), so the build steps run
    // without it; only the recipe tests, which are never published, get it (and LD_LIBRARY_PATH as well).
    env["CRT_PORT_RPATH_DIR"] = "";
    if (target.at("os") == "macos") {
        // The compiler is the external Xcode clang, started directly: unlike /usr/bin/clang it has no xcrun shim to find the OS
        // SDK, and the job environment has no xcrun. The declared SDK is handed over explicitly (libSystem lives there).
        auto os_sdk = port_os_sdk(toolchain);
        require(!os_sdk.empty() && fs::is_directory(os_sdk) && fs::exists(os_sdk / "SDKSettings.json"), "the macOS port build needs the configured OS SDK (SDKSettings.json)");
        require_plain_word(os_sdk.string(), "OS SDK path");
        env["SDKROOT"] = os_sdk.string();
    }
    if (target.at("os") == "windows") {
        // The Windows SDK import libraries (kernel32.lib, ...) are the host's, declared by the portable contract's OS SDK kind and
        // handed to the compiler wrapper explicitly, never found through a search path.
        auto os_sdk = port_os_sdk(toolchain);
        require(!os_sdk.empty() && fs::is_directory(os_sdk) && fs::exists(os_sdk / "kernel32.lib"), "the Windows port build needs the configured OS SDK import-library directory (kernel32.lib)");
        env["CRT_WINDOWS_SDK_LIBPATH"] = word(os_sdk);
    }
    for (const auto& item : flag_defaults()) env[item.first] = item.second;
    PortPlaceholders placeholders{word(prefix), env["CC"]};
    apply_port_env(env, recipe.env, placeholders);
    apply_port_env(env, port_executor_env(port_adapter_for(recipe.recipe_sha256), recipe.target_os), placeholders);
    return env;
}

PortBuildResult run_port_build(const PortBuildRequest& request) {
    require(request.toolchain && request.tools, "port build needs a toolchain and host tools");
    const auto& recipe = request.recipe;
    const auto host_os = native_target().at("os").get<std::string>();
    require(host_os == "linux" || host_os == "macos" || host_os == "windows", "the port executor supports Linux, macOS and Windows hosts");
    require(recipe.target_os == host_os, "the recipe was parsed for another OS than this host");
    const auto adapter_ = port_adapter_for(recipe.recipe_sha256);
    auto job = fs::absolute(request.job).lexically_normal();
    require(!fs::exists(job) && !fs::is_symlink(job), "port build job must be a new path");
    for (const auto& root : {request.tools->root, request.toolchain->sdk}) {
        auto relative = job.lexically_relative(root);
        require(relative.empty() || *relative.begin() == "..", "port build job must be outside the host tools and the SDK");
    }
    require(fs::is_directory(request.source_tree / recipe.source.source_dir), "pristine source tree is missing " + recipe.source.source_dir);

    // The recipe tests' sources must be the ones the adapter table pins; check before spending a build on them.
    for (const auto& test : recipe.tests) {
        auto source_file = request.test_root / test.source;
        auto pin = adapter_.test_sources.find(test.source);
        require(pin != adapter_.test_sources.end(), "test source is not pinned by the adapter table: " + test.source);
        require(fs::is_regular_file(source_file) && !fs::is_symlink(source_file), "test source is missing: " + source_file.string());
        require(file_sha256(source_file) == pin->second, "test source digest mismatch: " + test.source);
    }

    request.tools->create_job(job);
    job = fs::canonical(job);
    PortBuildRequest bound = request;
    bound.job = job;
    auto work = job / "work", prefix = job / "prefix", logs = job / "logs", tests = job / "tests";
    for (const auto& directory : {work, prefix, logs, tests}) fs::create_directory(directory);
    fs::create_directory_symlink(request.toolchain->sdk, job / "rootfs" / "crt-sdk");
    fs::create_directory(job / "rootfs" / "crt-bin");
    if (host_os == "windows") {
        const auto linker = word(request.toolchain->linker);
        require(linker.find('\'') == std::string::npos && word(request.toolchain->archiver).find('\'') == std::string::npos,
                "tool paths must not contain a single quote");
        write_text(job / "rootfs" / "crt-bin" / "crt-ar", tool_script(word(request.toolchain->archiver)));
        write_text(job / "rootfs" / "crt-bin" / "crt-ranlib", tool_script(word(ranlib_beside(request.toolchain->archiver))));
    } else {
        require_plain_word(request.toolchain->linker.string(), "toolchain path");
    }
    for (const auto& name : {"crt-cc", "crt-c++"})
        write_text(job / "rootfs" / "crt-bin" / name, wrapper_script(shell_path(*request.tools), std::string("/crt-sdk/tools/") + name, word(request.toolchain->linker)));
    auto source = work / recipe.source.source_dir;
    fs::copy(request.source_tree / recipe.source.source_dir, source, fs::copy_options::recursive | fs::copy_options::copy_symlinks);

    auto env = port_build_environment(bound, prefix);
    auto base = request.tools->environment(job, request.toolchain->sdk);
    auto child = as_child(env, base);
    PortPlaceholders placeholders{word(prefix), env.at("CC")};
    Runner runner{bound, job, logs, Json::array()};
    auto shell = word(inside(request.tools->root, request.tools->manifest.at("tools").at("shell")));
    auto make = word(inside(request.tools->root, request.tools->manifest.at("tools").at("make")));
    unsigned jobs = choose_jobs(request.jobs);
    Json patches = Json::array(), test_results = Json::array();

    std::vector<std::string> configure{shell, "./configure"};
    for (const auto& arg : recipe.configure_args) configure.push_back(substitute_port_placeholders(arg, placeholders));
    configure.push_back("--prefix=" + word(prefix));
    runner.run("configure", configure, child, source);

    for (const auto& patch : recipe.post_configure_patch) {
        auto target = source / patch.file;
        require(fs::is_regular_file(target) && !fs::is_symlink(target), "post_configure_patch target is not a regular file: " + patch.file);
        auto text = read_text(target);
        auto find = substitute_port_placeholders(patch.find, placeholders);
        auto replace = substitute_port_placeholders(patch.replace, placeholders);
        require(!find.empty() && text.find(find) != std::string::npos,
                "post_configure_patch text not found in " + patch.file + " (" + patch.reason + ")");
        size_t count = 0;
        for (size_t at = 0; (at = text.find(find, at)) != std::string::npos; at += replace.size()) { text.replace(at, find.size(), replace); ++count; }
        write_text(target, text);
        patches.push_back({{"file", patch.file}, {"reason", patch.reason}, {"replacements", count}});
    }

    // Executor-added make arguments (the literal @AR@ is the configured archiver) follow the recipe's own.
    std::vector<std::string> executor_args;
    for (auto arg : port_executor_make_args(adapter_, recipe.target_os)) {
        for (size_t at = 0; (at = arg.find("@AR@", at)) != std::string::npos; at += request.toolchain->archiver.string().size())
            arg.replace(at, 4, request.toolchain->archiver.string());
        executor_args.push_back(arg);
    }
    std::vector<std::string> build{make, "-j", std::to_string(jobs)};
    for (const auto& arg : recipe.make_args) build.push_back(substitute_port_placeholders(arg, placeholders));
    build.insert(build.end(), executor_args.begin(), executor_args.end());
    runner.run("make", build, child, source);
    std::vector<std::string> install{make, "install"};
    for (const auto& arg : recipe.make_args) install.push_back(substitute_port_placeholders(arg, placeholders));
    install.insert(install.end(), executor_args.begin(), executor_args.end());
    runner.run("make-install", install, child, source);

    // Recipe tests: compile with the same SDK wrapper, run with the port's library directory first in the loader path.
    for (const auto& test : recipe.tests) {
        auto source_file = request.test_root / test.source;
        // A Windows program must carry .exe: CreateProcess appends it to a name without an extension.
        auto binary = tests / (test.name + (host_os == "windows" ? ".exe" : ""));
        std::vector<std::string> compile{shell, word(job / "rootfs" / "crt-bin" / "crt-cc")};
        for (const auto& flag : test.cflags) compile.push_back(substitute_port_placeholders(flag, placeholders));
        compile.push_back(word(source_file));
        for (const auto& arg : test.link_args) compile.push_back(substitute_port_placeholders(arg, placeholders));
        compile.push_back("-o");
        compile.push_back(word(binary));
        auto compile_env = env;
        compile_env["CRT_PORT_RPATH_DIR"] = word(prefix / "lib");
        runner.run("test-build-" + test.name, compile, as_child(compile_env, base), tests);
        auto run_env = env;
        // Linux resolves the port's shared object through the loader path; macOS through the LC_RPATH crt-cc stamped above
        // (DYLD_* variables are neither needed nor reliable there).
        if (host_os == "linux") run_env["LD_LIBRARY_PATH"] = (prefix / "lib").string();
        // Windows has neither: the loader searches PATH (native syntax) for the port's DLL and for the SDK's shared runtime.
        if (host_os == "windows") run_env["PATH"] = (prefix / "lib").string() + ";" + (request.toolchain->sdk / "bin").string();
        auto result = runner.run("test-run-" + test.name, {word(binary)}, as_child(run_env, base), tests);
        // Like the oracle, the expected text must appear in the output (a fragment, not the whole line).
        bool ok = result.output.find(test.expect_stdout) != std::string::npos;
        test_results.push_back({{"name", test.name}, {"expected", test.expect_stdout}, {"actual", trim_end(result.output)}, {"passed", ok}});
        if (!ok) throw Error("port test '" + test.name + "' printed an unexpected line: " + trim_end(result.output));
    }

    Json environment = Json::object();
    std::set<std::string> inherited(base.inherited_names.begin(), base.inherited_names.end());
    for (const auto& item : env) environment[item.first] = inherited.count(item.first) ? Json("(inherited)") : Json(item.second);
    Json record{{"recipe", {{"name", recipe.name}, {"version", recipe.version}, {"sha256", recipe.recipe_sha256}}},
                {"job", job.string()}, {"jobs", jobs}, {"steps", runner.steps}, {"patches", patches},
                {"environment", environment}, {"tests", test_results}, {"prefix_inventory", inventory(prefix)},
                {"host_tools", request.tools->identity()}};
    return {prefix, logs, record};
}


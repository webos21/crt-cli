// Commands in this slice are handed to configure/make as unquoted words (zlib's Makefile expands $(AR) and $(RANLIB)
// unquoted), so a host tool path must be one shell word. A CLI-side alias or compiler bridge is the later answer.
void require_plain_word(const std::string& value, const std::string& what) {
    static const std::string forbidden = " \t\r\n\"'`$\\;&|<>()*?[]{}!#~";
    require(!value.empty() && value.find_first_of(forbidden) == std::string::npos,
            what + " must be a single shell word without whitespace or shell metacharacters: " + value);
}

// llvm-ar -> llvm-ranlib in the same directory (llvm-ar-21 -> llvm-ranlib-21), required to exist.
fs::path ranlib_beside(const fs::path& archiver) {
    auto name = archiver.filename().string();
    auto at = name.find("llvm-ar");
    require(at != std::string::npos, "cannot derive llvm-ranlib from the archiver name: " + name);
    name.replace(at, 7, "llvm-ranlib");
    auto result = archiver.parent_path() / name;
    require(fs::exists(result), "llvm-ranlib not found beside the archiver: " + result.string());
    native_executable(result);
    return result;
}

// The SDK wrappers take the linker as an ordinary argument and a configure script's link probes do not all carry LDFLAGS,
// so each job gets its own thin wrappers that name the configured linker on every non-compile-only invocation (the same
// -c/-E/-S rule crt-cc uses; --ld-path on a compile-only command is an unused-argument warning, which breaks configure's
// "no output" probes). They are started as `<bundle sh> <script>`, so no shebang is involved.
std::string wrapper_script(const std::string& shell, const std::string& wrapped, const std::string& linker) {
    return "# generated by crt-cli for one port build job\n"
           "compile_only=0\n"
           "for arg in \"$@\"; do\n"
           "  case \"$arg\" in -c|-E|-S) compile_only=1 ;; esac\n"
           "done\n"
           "if [ \"$compile_only\" -eq 0 ]; then set -- \"$@\" '--ld-path=" + linker + "'; fi\n"
           "exec " + shell + " " + wrapped + " \"$@\"\n";
}

std::string shell_path(const HostTools& tools) { return tools.manifest.at("rootfs").at("shell").get<std::string>(); }

unsigned choose_jobs(unsigned requested) {
    if (requested) return requested;
    unsigned hardware = std::thread::hardware_concurrency();
    return std::max(1u, std::min(hardware ? hardware : 1u, 8u));
}

std::string tail(const std::string& text, size_t lines) {
    size_t end = text.size(), count = 0;
    while (end > 0 && count <= lines) { end = text.rfind('\n', end - 1); if (end == std::string::npos) return text; ++count; }
    return text.substr(end + 1);
}

struct Runner {
    const PortBuildRequest& request;
    fs::path job, logs;
    Json steps = Json::array();

    // Runs `argv` (argv[0] a real native executable) with stdout and stderr merged by a one-line trampoline in the
    // bundle's shell, so the step log holds everything the step printed.
    ProcessResult run(const std::string& name, const std::vector<std::string>& argv, const ChildEnvironment& environment,
                      const fs::path& directory) {
        std::vector<std::string> wrapped{inside(request.tools->root, request.tools->manifest.at("tools").at("shell")).string(),
                                         "-c", "exec \"$@\" 2>&1 </dev/null", "crt-port-step"};
        wrapped.insert(wrapped.end(), argv.begin(), argv.end());
        auto started = std::chrono::steady_clock::now();
        auto result = execute_child(wrapped, environment, directory, request.step_timeout_seconds, false);
        double seconds = std::chrono::duration<double>(std::chrono::steady_clock::now() - started).count();
        auto log = logs / (std::to_string(steps.size() + 1) + "-" + name + ".log");
        write_text(log, result.output);
        steps.push_back({{"name", name}, {"argv", argv}, {"exit_code", result.exit_code}, {"timed_out", result.timed_out},
                         {"log", log.filename().string()}, {"log_truncated", result.output_truncated}, {"seconds", seconds}});
        if (result.exit_code != 0)
            throw Error("port build step '" + name + "' failed (exit " + std::to_string(result.exit_code) +
                        (result.timed_out ? ", timed out" : "") + "); log: " + log.string() + "\n" + tail(result.output, 20));
        return result;
    }
};

ChildEnvironment as_child(const std::map<std::string, std::string>& values, const ChildEnvironment& original) {
    ChildEnvironment result{{}, original.fixed, original.inherited_names};
    for (const auto& item : values) result.values.push_back(item.first + "=" + item.second);
    return result;
}

std::string trim_end(std::string value) {
    while (!value.empty() && (value.back() == '\n' || value.back() == '\r')) value.pop_back();
    return value;
}

